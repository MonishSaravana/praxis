def pct(x, d=0):
    return "n/a" if x is None else f"{100 * x:.{d}f}%"


def num(x, d=2):
    return "n/a" if x is None else f"{x:.{d}f}"


def lat(d, unit="s", k=("p50", "p95"), scale=1.0, dd=1):
    if not d or d.get("p50") is None:
        return "n/a"
    return " / ".join(f"{d[x] * scale:.{dd}f} {unit}" for x in k)


def src(m, key):
    return f"`{m['_sources'].get(key, '?')}`"


def table(rows: list[list[str]], head: list[str]) -> str:
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def _jload(rel: str):
    p = RESULTS / rel
    return json.loads(p.read_text()) if p.exists() else None


