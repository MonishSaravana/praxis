"""Write results/RESULTS.md (numbers section) and docs/CLAIMS.md from results/metrics.json.

Every number is formatted from metrics.json (which records the source file of each entry). Narrative text that
depends on a comparison (e.g. "beats") is chosen by code from the numbers, so it cannot drift from the data.
The qualitative failure analysis lives in results/FAILURES.md (written from inspected run logs)."""
from __future__ import annotations

